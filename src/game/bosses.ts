/**
 * 보스.
 *
 * 예전 보스 웨이브는 "적 수를 반으로 줄이고 스탯 1.35배"였다. 그래서 통과율이
 * 96%로 이 게임에서 가장 안전한 웨이브 중 하나였고, 벽이 아니라 사건이라는
 * 원래 의도에는 맞았지만 **잴 것이 없었다** — 개입을 만들어도 통과율을 15%p
 * 올릴 여지가 3%p밖에 없었다.
 *
 * 그래서 보스를 **한 마리의 큰 것**으로 다시 만든다. 3x3 칸을 차지하고 체력이
 * 두껍고 오래 싸운다. 통과율을 조절할 손잡이(`balance.ts`의 보스 항목)를 두어
 * 개입의 값을 측정할 수 있게 하는 것이 핵심이다.
 *
 * 스프라이트는 시트에서 잘라 두고 쓰지 않던 09~20번을 쓴다. 낯선 고양이가
 * 크게 앉아 있으면 "보스가 나왔다"가 한 컷에 읽힌다.
 *
 * 보스도 그냥 `Cat`이다. 별도 타입을 만들면 타겟팅·이동·피해 판정을 전부 다시
 * 써야 하는데, 반경 하나만 추가하면 기존 전투 로직이 그대로 돈다.
 */
/**
 * 보스마다 다른 기믹 조합.
 *
 * 같은 보스가 반복되면 두 번째부터는 그냥 체력 많은 적이다. 레이드의 재미는
 * **"이 보스는 이렇게 잡는다"가 학습되는 것**이고, 그러려면 보스마다 요구하는
 * 대응이 달라야 한다.
 *
 * 축을 세 개만 둔다 — 예고 패턴 순서, 순간이동 빈도, 취약 창의 길이와 시점.
 * 축이 더 늘면 플레이어가 무엇이 다른지 못 읽는다.
 */
export interface BossKit {
  /**
   * 이 보스의 강도 배수. 체력과 광역 피해에 함께 곱한다.
   *
   * 기믹이 다르면 같은 수치라도 체감이 다르다. 실측에서 무쇠발톱은 통과율
   * 100%, 살금이는 45%가 나왔다 — 순간이동이 근접의 시간을 갉아먹기 때문이다.
   * 기믹을 손대는 대신 여기서 저울을 맞춘다. 다만 **평탄하게 맞추려 하지는
   * 않는다** — 살금이는 램프에 가파르게 반응하고(6웨이브 95% → 15웨이브 45%)
   * 무쇠발톱은 완만하다(3웨이브 85% → 12웨이브 100%). 순간이동이 근접의
   * 시간을 갉아먹는 정도가 팀 크기에 따라 달라지기 때문이고, 그건 기믹의
   * 성격이지 결함이 아니다. 집계 통과율만 목표에 두고 편차는 남긴다.
   */
  readonly power: number;
  /**
   * 문턱마다 순환할 예고 패턴.
   *
   * `"gather"`는 원형이되 **안으로 들어가야 하는** 예고다. 흩어짐만 있으면
   * 예고가 뜰 때마다 그냥 누르면 되므로 판단이 없다.
   */
  /**
   * 예고 패턴 차례.
   *
   * `gather`는 안에 있어야 하고 나머지는 피해야 한다. `stomp`는 **보스 발밑**에
   * 생기는 원형이다 — 다른 넷이 전부 팀을 따라오는 것과 달리 이것만 자리가
   * 고정이라, **보스에게서 얼마나 떨어져 서느냐**가 대형의 결정이 된다.
   */
  readonly patterns: readonly (TelegraphShape | "gather" | "stomp" | "hearth" | "quake")[];
  /**
   * 페이즈 2(문턱 인덱스 3부터 — battle.ts PHASE2_FROM_IDX)에서 바꿔 도는 패턴 차례. 없으면 페이즈 내내
   * `patterns`만 돈다.
   *
   * **스테이지 우두머리(`Cat.stageBoss`)에게만 적용된다.** 중간보스는 걸음
   * 하나를 채우는 자리라 성격이 끝까지 같아야 "이 보스는 이렇게 잡는다"가
   * 흔들리지 않는다. 전환의 무게는 걸음의 끝(우두머리)에만 실린다.
   *
   * `battle.ts`의 `makeTelegraph`가 `boss.thresholdIdx`를 그대로 이어서
   * 이 배열에 돌린다 — 페이즈 2 진입이 인덱스 0부터 다시 시작하지 않고
   * 문턱 순번 중간에서 이어받는다. 패턴은 순환표일 뿐 서사적 순서가 아니므로
   * 문제가 안 된다.
   */
  readonly phase2Patterns?: readonly (TelegraphShape | "gather" | "stomp" | "hearth" | "quake")[];
  /** 문턱 몇 개마다 순간이동하는가. 0이면 안 한다 */
  readonly teleportEvery: number;
  /** 취약 창이 열리는 체력 비율 */
  readonly vulnerableAt: number;
  /** 취약 창 길이(ms) */
  readonly vulnerableMs: number;
}

